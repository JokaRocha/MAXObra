create policy obras_read_roles on public.obras
    for select to authenticated
    using (
        user_id = (select auth.uid())
        and coalesce(((select auth.jwt()) -> 'app_metadata' ->> 'role'), 'info')
            in ('manager', 'builder', 'info')
    );

create policy obras_insert_roles on public.obras
    for insert to authenticated
    with check (
        user_id = (select auth.uid())
        and coalesce(((select auth.jwt()) -> 'app_metadata' ->> 'role'), 'info')
            in ('manager', 'builder')
    );

create policy obras_update_roles on public.obras
    for update to authenticated
    using (
        user_id = (select auth.uid())
        and coalesce(((select auth.jwt()) -> 'app_metadata' ->> 'role'), 'info')
