create table if not exists public.obras (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
    nome text not null,
    cliente text not null default '',
    local text not null default '',
    gestor text not null default '',
    data_inicio date,
    data_fim date,
    valor_obra numeric(14, 2) not null default 0 check (valor_obra >= 0),
    tipo_iva text not null default 'Sem IVA',
    iva numeric(5, 2) not null default 0 check (iva >= 0 and iva <= 100),
    status text not null default 'Planeamento',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (id, user_id)
);

create table if not exists public.movimentos_financeiros (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid(),
    obra_id bigint not null,
    tipo text not null check (tipo in ('Receita', 'Despesa')),
    descricao text not null,
    categoria text not null,
    valor numeric(14, 2) not null check (valor >= 0),
    data date not null,
    observacoes text not null default '',
    created_at timestamptz not null default now(),
    foreign key (obra_id, user_id)
        references public.obras (id, user_id) on delete cascade
);

create table if not exists public.tarefas (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid(),
    obra_id bigint not null,
    titulo text not null,
    descricao text not null default '',
    responsavel text not null,
    prioridade text not null default 'Média',
    data_inicio date,
    data_fim date,
    status text not null default 'Pendente',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    foreign key (obra_id, user_id)
        references public.obras (id, user_id) on delete cascade
);

create index if not exists obras_user_id_idx
    on public.obras (user_id);
create index if not exists movimentos_financeiros_user_obra_data_idx
    on public.movimentos_financeiros (user_id, obra_id, data desc);
create index if not exists tarefas_user_obra_data_fim_idx
    on public.tarefas (user_id, obra_id, data_fim);

alter table public.obras enable row level security;
alter table public.movimentos_financeiros enable row level security;
alter table public.tarefas enable row level security;

revoke all on table
    public.obras,
    public.movimentos_financeiros,
    public.tarefas
from public, anon, authenticated;

grant select, insert, update, delete on table
    public.obras,
    public.movimentos_financeiros,
    public.tarefas
to authenticated;

grant select on table
    public.obras,
    public.movimentos_financeiros,
    public.tarefas
to anon;

